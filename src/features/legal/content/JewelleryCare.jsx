import { PolicySection } from '../PolicySection/PolicySection'

export default function JewelleryCare() {
  return (
    <PolicySection id="care-tips" title="Keep your pieces shining">
      <ul>
        <li>Wipe with a soft cloth after every use.</li>
        <li>Store in a closed pouch or box.</li>
        <li>Remove before swimming or showers, since chlorine and salt water dull the finish.</li>
        <li>Let perfume and lotion dry before putting your pieces on.</li>
        <li>Keep pearls, stones, and zircons away from knocks, as they are more delicate.</li>
        <li>Fasten necklace and bracelet clasps when storing to avoid tangles.</li>
      </ul>
    </PolicySection>
  )
}
